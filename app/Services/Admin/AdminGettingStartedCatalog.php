    /**
     * 目录中的全部分节 id，供页面锚点和测试使用。
     *
     * @return list<string>
     */
    public function sectionIds(): array
    {
        $ids = [];
        foreach ($this->document()['groups'] as $group) {
            foreach ($group['sections'] as $section) {
                $ids[] = (string) $section['id'];
            }
        }

        return $ids;
    }

