     */
    private function section(
        string $id,
        string $title,
        string $place,
        string $purpose,
        array $steps,
        string $outcome,
        array $related,
        array $flow,
        bool $protected = false,
        ?array $map = null,
    ): array {
        return [
            'id' => $id,
            'title' => $title,
            'protected' => $protected,
            'place' => $place,
            'purpose' => $purpose,
            'steps' => $steps,
            'outcome' => $outcome,
            'related' => $related,
            'flow' => $flow,
            'map' => $map,
        ];
    }
